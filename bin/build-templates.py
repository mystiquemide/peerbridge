#!/usr/bin/env python3
"""Writes the two Switch templates from template/instructions/*.md, so the
templates and setup.sh always give the agents the same instructions.
Run after editing an instructions file: bin/build-templates.py"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO_URL = "https://github.com/mystiquemide/peerbridge"

COMMON_PARAMS = """\
  provider:
    type: provider
    description: The coding agent that runs it. PeerBridge is tested with Codex.
    default: [codex, claude]
    input: advanced
  machine:
    type: machine
    description: The machine it runs on. For PeerBridge, your own.
    default: [$first]
    input: advanced
  directory:
    type: directory
    description: Its working directory. It clones PeerBridge here.
    default: "{$agents_dir}/{agent}"
    input: advanced
"""

BACKEND = """\
# PeerBridge, Dev A's side: backend-agent and the api-sync room.
#
# Dev A deploys this. backend-agent runs on Dev A's machine and is the only
# thing that can make Dev A's backend run a request. After deploying:
#   1. Start the sample backend from backend-agent's checkout and install the
#      wrapper: sudo bin/install-wrapper.sh <checkout>/sample/backend/access.log 8001
#   2. Apply backend-agent's addressing policy (README, "How Switch makes this
#      work"): its owner anywhere, agents in api-sync only, no other humans.
#      Template addressing can't express a room-scoped rule, so it starts as
#      owner-only here.
#   3. Add Dev B to api-sync. Dev B deploys peerbridge-frontend.template.yaml,
#      and Dev A adds frontend-agent to the room.
#
# Generated by bin/build-templates.py from template/instructions/backend-agent.md.
version: 1

params:
{common}  bridge:
    type: bridge
    description: Where api-sync is mirrored. Leave empty for a Switch-only room.
    default: [Mattermost, Slack, Discord, $first]
    required: false

agent:
  name: backend-agent
  display_name: backend-agent
  description: Runs allowlisted requests against Dev A's local backend, and fixes it when Dev A asks
  provider: "{{provider}}"
  machine: "{{machine}}"
  directory: "{{directory}}"
  repo: {repo}
  addressing: owner
  instructions: |
{instructions}
room:
  name: api-sync
  description: Dev A's and Dev B's agents test uncommitted frontend against uncommitted backend
  bridge: "{{bridge}}"
  agents: [backend-agent]
  users: ["{{$creator}}"]
"""

FRONTEND = """\
# PeerBridge, Dev B's side: frontend-agent.
#
# Dev B deploys this. frontend-agent runs on Dev B's machine, reads Dev B's
# frontend code, and asks backend-agent for the request it would send. It
# joins no room by itself: api-sync belongs to Dev A, so Dev A adds it. Its
# addressing is "anyone" so the members of its rooms, Dev A included, can
# reach it. It only reads code and posts requests.
#
# Generated by bin/build-templates.py from template/instructions/frontend-agent.md.
version: 1

params:
{common}
agent:
  name: frontend-agent
  display_name: frontend-agent
  description: Builds the request Dev B's frontend would send and asks backend-agent to run it
  provider: "{{provider}}"
  machine: "{{machine}}"
  directory: "{{directory}}"
  repo: {repo}
  addressing: anyone
  instructions: |
{instructions}"""


def indent(text: str) -> str:
    return "".join(("    " + line if line.strip() else "\n") if line != "\n" else "\n"
                   for line in text.splitlines(keepends=True))


def render(shape: str, instructions: Path) -> str:
    body = indent(instructions.read_text(encoding="utf-8"))
    if not body.endswith("\n"):
        body += "\n"
    return shape.format(common=COMMON_PARAMS, repo=REPO_URL, instructions=body)


TEMPLATES = {
    ROOT / "template" / "peerbridge-backend.template.yaml": (BACKEND, ROOT / "template" / "instructions" / "backend-agent.md"),
    ROOT / "template" / "peerbridge-frontend.template.yaml": (FRONTEND, ROOT / "template" / "instructions" / "frontend-agent.md"),
}

if __name__ == "__main__":
    for out, (shape, src) in TEMPLATES.items():
        out.write_text(render(shape, src), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
